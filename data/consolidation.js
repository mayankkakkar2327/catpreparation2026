function resolveInternal(href) {
  if (!href || (!href.startsWith('/') && !href.startsWith('https://www.catpreparation2026.com/'))) return href;
  const url = new URL(href, 'https://www.catpreparation2026.com');
  const key = url.pathname.replace(/\/?$/, '/');
  const destination = redirects[key];
  if (!destination) return href;
  const target = new URL(destination, url.origin);
  // Preserve campaign parameters; use the destination anchor for relocated FAQs.
  return target.pathname + url.search + (target.hash || url.hash);
}
function preparePages(input) {
  // Existing sources intentionally replace the blog index and one comparison.
  // Resolve that precedence once instead of writing the same route repeatedly.
  const unique = new Map(input.map(page => [page.slug, page]));
  for (const page of replacements) unique.set(page.slug, page);
  for (const from of Object.keys(redirects)) unique.delete(from.slice(1, -1));
  const pages = [...unique.values()];
  const titles = new Map(pages.map(p => [`/${p.slug}/`, p.title]));
  return pages.map(page => ({...page, sections: (page.sections || []).map(section => {
    if (page.slug !== 'blog' || !section.table) return section;
    const seen = new Set();
    return {...section, table: {...section.table, rows: section.table.rows.filter(row => {
      const link = row.find(cell => cell && typeof cell === 'object' && cell.href);
      if (!link) return true;
      const href = resolveInternal(link.href);
      if (seen.has(href)) return false;
      seen.add(href); return true;
    }).map(row => {
      const link = row.find(cell => cell && typeof cell === 'object' && cell.href);
      if (!link) return row;
      const href = resolveInternal(link.href);
      const target = pages.find(p => `/${p.slug}/` === href);
      return target ? [titles.get(href), target.description, {...link, href}] : row;
    })}};
  })}));
}
